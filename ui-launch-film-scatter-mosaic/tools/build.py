#!/usr/bin/env python3
"""index.tpl + assets/words.json -> index.html, with every scene time derived from word times.

Why: HyperFrames reads data-start / data-duration from the HTML, so when you swap the voice file
(a different speaker = different word times) every hard-coded section time goes stale. Here the
template declares named times once and uses {{expressions}} everywhere:

  <!--TIMES
  s2 = w(10) - 0.15        # w(i) = start of word i + VO
  s3 = w(14) - 0.35
  END = w(137) + 3.3
  TIMES-->
  <section data-start="{{s2}}" data-duration="{{s3 - s2}}">

The JS gets the same values:  /*W*/[]/*W*/ -> [[word, start], ...]  and  /*T*/{}/*T*/ -> {"s2": 2.87, ...}

Usage: python3 tools/build.py            (run in the project folder; VO offset from <!--VO 0.3-->)
"""
import json
import re

tpl = open("index.tpl", encoding="utf-8").read()
W = json.load(open("assets/words.json", encoding="utf-8"))
VO = float(re.search(r"<!--VO\s+([\d.]+)\s*-->", tpl).group(1))
env = {"w": lambda i: W[i][1] + VO, "e": lambda i: W[i][2] + VO, "VO": VO}

block = re.search(r"<!--TIMES(.*?)TIMES-->", tpl, re.S)
T = {}
for line in block.group(1).splitlines():
    line = line.split("#")[0].strip()
    if not line:
        continue
    k, expr = [s.strip() for s in line.split("=", 1)]
    T[k] = round(eval(expr, {}, {**env, **T}), 3)
env.update(T)


def sub(m):
    v = eval(m.group(1), {}, env)
    return f"{v:.3f}".rstrip("0").rstrip(".") if isinstance(v, float) else str(v)


html = re.sub(r"\{\{(.*?)\}\}", sub, tpl)
html = re.sub(r"/\*W\*/.*?/\*W\*/", "/*W*/" + json.dumps([[x[0], x[1]] for x in W], ensure_ascii=False) + "/*W*/", html, flags=re.S)
html = re.sub(r"/\*T\*/.*?/\*T\*/", "/*T*/" + json.dumps(T) + "/*T*/", html, flags=re.S)
html = html.replace(block.group(0), "<!-- times generated by tools/build.py from index.tpl -->")
open("index.html", "w", encoding="utf-8").write(html)
print("index.html written;", ", ".join(f"{k}={v}" for k, v in T.items()))
